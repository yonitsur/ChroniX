const loadedLanguages = new Set();
const inflightLanguageLoads = {};

export function detectSystemLanguage() {
  if (typeof navigator === 'undefined') return 'en';
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language];
  const primary = String(langs[0] || '').toLowerCase();
  // 'iw' is the legacy code for Hebrew still reported by some Android devices
  return primary.startsWith('he') || primary.startsWith('iw') ? 'he' : 'en';
}

export function detectInitialLanguage() {
  try {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem('chronix_lang');
      const isManual = localStorage.getItem('chronix_lang_manual') === 'true';
      // Before auto-detection existed the default was 'en', so a saved 'he' was an explicit choice
      if (saved && SUPPORTED_LANGUAGES.some((l) => l.code === saved) && (isManual || saved === 'he')) {
        return saved;
      }
    }
    return detectSystemLanguage();
  } catch {
    return detectSystemLanguage();
  }
}

export function isLanguageLoaded(lang) {
  return loadedLanguages.has(lang === 'he' ? 'he' : 'en');
}

export function ensureLanguageLoaded(lang) {
  const code = lang === 'he' ? 'he' : 'en';
  if (loadedLanguages.has(code)) {
    return Promise.resolve(translations[code]);
  }
  if (inflightLanguageLoads[code]) {
    return inflightLanguageLoads[code];
  }
  const loader = code === 'he' ? import('./he.js') : import('./en.js');
  inflightLanguageLoads[code] = loader
    .then((mod) => {
      const bundle = mod?.[code] || mod?.default;
      if (bundle) {
        translations[code] = bundle;
        loadedLanguages.add(code);
      }
      delete inflightLanguageLoads[code];
      return translations[code];
    })
    .catch((err) => {
      delete inflightLanguageLoads[code];
      console.error(`Failed to load locale bundle "${code}":`, err);
      return translations[code];
    });
  return inflightLanguageLoads[code];
}
