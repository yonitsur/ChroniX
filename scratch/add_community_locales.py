import json

def update_locales():
    for lang, content in DATA.items():
        file_path = LOCALES_DIR / f"{lang}.js"
        if not file_path.exists():
            print(f"File not found: {file_path}")
            continue

        with open(file_path, "r", encoding="utf-8") as f:
            code = f.read()

        # 1. Update exploreCommunity in home if missing
        if '"exploreCommunity":' not in code:
            explore_str = content["exploreCommunity"]
            code = re.sub(
                r'("surpriseMe":\s*"[^"]*")',
                r'\1,\n    "exploreCommunity": ' + json.dumps(explore_str, ensure_ascii=False),
                code
            )

        # 2. Add community and comments before final `};` if not present
        if '"community":' not in code:
            comm_json = json.dumps(content["community"], indent=4, ensure_ascii=False)
            # Indent each line by 2 spaces
            comm_indented = "\n".join("  " + line for line in comm_json.split("\n"))

            comm_block = f',\n  "community": {comm_indented.strip()}'

            if '"comments":' not in code:
                comments_json = json.dumps(content["comments"], indent=4, ensure_ascii=False)
                comments_indented = "\n".join("  " + line for line in comments_json.split("\n"))
                comm_block += f',\n  "comments": {comments_indented.strip()}'

            # Insert before last closing `};`
            code = re.sub(r'\n\};\s*$', f'{comm_block}\n}};\n', code)

        with open(file_path, "w", encoding="utf-8") as f:
            f.write(code)
        print(f"Successfully updated {lang}.js")

if __name__ == "__main__":
    update_locales()
